"""
This program compares two given numbers
and prints whether the first number is
greater, less then or equal to second
"""

first_number = 200

second_number = 1000

if first_number > second_number:
    print("First number is greater then second number.")
elif first_number < second_number:
    print("First number is less then second number.")
else:
    print("First number is equal to second number.")