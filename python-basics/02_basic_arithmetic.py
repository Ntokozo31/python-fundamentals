"""
This program calculates and print results of
addition, subtration, normal division, integer division
and modulo
"""

a = 25

b = 7

print(f"Addition: {a + b}")
print(f"Subtraction: {a - 2}")
print(f"Multiplication: {a * b}")
print(f"Normal division: {a / b}")
print(f"Integer division: {a // b}")
print(f"Modulo: {a % b}")