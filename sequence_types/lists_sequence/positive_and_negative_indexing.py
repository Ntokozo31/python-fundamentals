"""
This program  create a list of 4 colours.  
Print the item at index 0, index 2, and the last item using negative indexing.
"""


colours = ["Yellow", "Brown", "Red", "Green"]

print(f"Item at index 0 is: {colours[0]}")
print(f"Item at index 2 is: {colours[2]}")
print(f"Last item is: {colours[-1]}")
